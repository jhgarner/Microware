fun durableIdFromEmojis(emojis: String): DurableId {
    val digits = mutableListOf<Int>()
    var position = 0

    while (position < emojis.length) {
        val (emoji, digit) = encodingByLength.firstOrNull { (character, _) ->
            emojis.startsWith(character, position)
        } ?: error("Unknown character in durable ID")

        digits += digit
        position += emoji.length
    }

    require(digits.isNotEmpty()) { "A durable ID must include its parity character" }
    val parityDigit = digits.removeAt(digits.lastIndex)
    require(digits.isNotEmpty()) { "A durable ID must include an encoded value" }
    require(parityDigit == parityDigitFor(digits)) { "Durable ID parity check failed" }

    var value = 0uL
    for (digit in digits) {
        val unsignedDigit = digit.toULong()
        require(value <= (ULong.MAX_VALUE - unsignedDigit) / encodingRadix) {
            "Durable ID is too large"
        }
        value = value * encodingRadix + unsignedDigit
    }

    return DurableId(value.toLong())
}

fun durableIdToEmojis(durableId: DurableId): String {
    var value = durableId.bits.toULong()
    val digits = mutableListOf<Int>()

    do {
        digits += (value % encodingRadix).toInt()
        value /= encodingRadix
    } while (value > 0uL)

    digits.reverse()
    digits += parityDigitFor(digits)
    return digits.joinToString(separator = "") { encodingAlphabet[it] }
}

private fun parityDigitFor(digits: List<Int>): Int {
    val sum = digits.fold(0uL) { total, digit ->
        (total + digit.toULong()) % encodingRadix
    }
    return ((encodingRadix - sum) % encodingRadix).toInt()
}

